/**
 * Generate a mock MP3 buffer (repeats the silent frame to reach ~16KB)
 */
function getMockAudioBuffer() {
  const repeatCount = 50; // ~16KB
  const buffers = [];
  for (let i = 0; i < repeatCount; i++) {
    buffers.push(SILENT_MP3_FRAME);
  }
  return Buffer.concat(buffers);
}

/**
 * Generate mock word timings for a given text
 * @param {string} text - Input text
 * @param {number} speakingRate - Speaking rate multiplier
 * @returns {Array} Word timing array
 */
function generateMockWordTimings(text, speakingRate = 1.0) {
  const words = (text || '').split(/\s+/).filter(w => w.length > 0);
  const avgWordDuration = 0.4 / speakingRate;
  const timings = [];
  let currentTime = 0;

  for (let i = 0; i < words.length; i++) {
    const word = words[i].replace(/[^\w]/g, '').trim();
    if (!word) continue;

    const endTime = currentTime + avgWordDuration;
    timings.push({
      word,
      timeSeconds: currentTime,
      endTimeSeconds: endTime,
      markName: `word_${i}`,
      hasDirectTiming: true,
    });
    currentTime = endTime;
  }

  return timings;
}

/**
 * Mock synthesizeWithGoogle response
 * @param {object} options - TTS options
 * @returns {object} Mock TTS result
 */
function getMockSynthesizeResult(options) {
  const { text = '', speakingRate = 1.0, voiceName = 'en-US-Standard-C' } = options;
  const wordTimings = generateMockWordTimings(text, speakingRate);
  const cleanWords = wordTimings.map(w => w.word);
  const totalDuration = wordTimings.length > 0
    ? wordTimings[wordTimings.length - 1].endTimeSeconds
    : 0;

  return {
    audioContent: getMockAudioBuffer(),
    wordTimings,
    cleanWords,
    originalWords: (text || '').split(/\s+/).filter(w => w.length > 0),
    totalDuration,
    speakingRate,
    voiceName,
    actualGender: 'FEMALE',
    timingMethod: 'Load Test Mock',
    success: true,
  };
}

